"""
BUDDY AI — Groq Cloud AI Service

Architecture & Inference Pipeline:
  - Ultra-High Speed Groq LPU Inference:
      - Delivers conversational tokens at >500 tokens/second for near-instant dialogue responses.
      - Operates via OpenAI-compatible REST completions endpoint (`https://api.groq.com/openai/v1/chat/completions`).
  - Resilient Rate-Limiting & Adaptive Cooldown:
      - Intercepts HTTP 429 Too Many Requests and automatically engages a 20-second cooldown window
        to prevent spamming the provider and facilitate instant fallback to alternate engines.
      - Supports transparent model fallback (e.g. switching to backup models on 404/429 status).
  - Reasoning Trace Cleansing:
      - Filters internal reasoning blocks (`<think>...</think>`) and unifies Unicode non-breaking spaces.
  - Strict Schema Sanitization:
      - Normalizes message history to strictly conform with OpenAI tool-calling specifications,
        ensuring `tool_call_id` is present on all tool-role turns and JSON stringifying arguments.
"""

import re
import json
import httpx
import logging
from typing import Dict, Any, List, Optional
from ..config import settings

import time

logger = logging.getLogger("buddy.groq")

GROQ_API_BASE = "https://api.groq.com/openai/v1/chat/completions"
_groq_rate_limited_until = 0.0


def is_groq_available() -> bool:
    """
    Checks if Groq API is enabled, supplied with a valid API key, and not currently
    cooling down from an active rate-limit event.

    Returns:
        bool: True if Groq can accept inference requests.
    """
    global _groq_rate_limited_until
    if time.time() < _groq_rate_limited_until:
        return False
    return bool(settings.GROQ_ENABLED and settings.GROQ_API_KEY and len(settings.GROQ_API_KEY.strip()) > 10)


def reset_groq_quota():
    """
    Manually resets the rate limit cooldown timer, enabling immediate retries.
    """
    global _groq_rate_limited_until
    _groq_rate_limited_until = 0.0


def _clean_reasoning_tags(text: str) -> str:
    """
    Strips internal `<think>...</think>` reasoning trace blocks from final model output.
    Normalizes Unicode non-breaking and thin spaces into standard ASCII spaces.

    Args:
        text: Raw text generated by reasoning LLM models.

    Returns:
        str: Cleaned user-facing dialogue text.
    """
    if not text:
        return ""
    cleaned = re.sub(r"<think>[\s\S]*?</think>", "", text)
    cleaned = re.sub(r"[\u202f\u00a0\u2000-\u200b]", " ", cleaned)
    return cleaned.strip()


def _prepare_messages_for_groq(messages: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """
    Sanitizes conversation messages to conform strictly to the OpenAI/Groq API schema.
    Ensures tool responses include valid `tool_call_id` and stringified function arguments.

    Args:
        messages: List of raw conversation turns from the session history.

    Returns:
        List[Dict[str, Any]]: Validated list of OpenAI-compliant message dictionaries.
    """
    clean_msgs = []
    for msg in messages:
        role = msg.get("role", "user")
        content = msg.get("content")
        tool_calls = msg.get("tool_calls")
        tool_call_id = msg.get("tool_call_id")
        name = msg.get("name")

        item: Dict[str, Any] = {"role": role}

        if role == "tool":
            item["content"] = str(content or "")
            item["tool_call_id"] = tool_call_id or "call_default"
            if name:
                item["name"] = name
        elif role == "assistant":
            item["content"] = content if content is not None else ""
            if tool_calls:
                clean_tool_calls = []
                for tc in tool_calls:
                    if isinstance(tc, dict):
                        tc_clean = dict(tc)
                        fn = tc_clean.get("function")
                        if isinstance(fn, dict):
                            fn_clean = dict(fn)
                            args = fn_clean.get("arguments")
                            if isinstance(args, dict):
                                fn_clean["arguments"] = json.dumps(args)
                            elif args is None:
                                fn_clean["arguments"] = "{}"
                            elif not isinstance(args, str):
                                fn_clean["arguments"] = str(args)
                            tc_clean["function"] = fn_clean
                        clean_tool_calls.append(tc_clean)
                    else:
                        clean_tool_calls.append(tc)
                item["tool_calls"] = clean_tool_calls
        else:
            item["content"] = str(content or "")

        clean_msgs.append(item)
    return clean_msgs


async def call_groq_chat(
    messages: List[Dict[str, Any]],
    tools: Optional[List[Dict[str, Any]]] = None,
    temperature: float = 0.3,
    max_tokens: int = 1500
) -> Dict[str, Any]:
    """
    Executes a high-speed chat completion request against Groq LPUs.
    Supports OpenAI-compatible function calling, automatic model failover, and rate-limit backoff.

    Args:
        messages: Preceding multi-turn dialogue message list.
        tools: Optional list of function tool schemas for agent tool calling.
        temperature: Sampling randomness parameter (default: 0.3 for focused factual output).
        max_tokens: Maximum token generation ceiling.

    Returns:
        Dict[str, Any]: Assistant message dictionary with 'role', 'content', and optional 'tool_calls'.

    Raises:
        RuntimeError: If Groq is unavailable, rate-limited, or returns non-200 responses.
    """
    global _groq_quota_exceeded
    if not is_groq_available():
        raise RuntimeError("Groq API is not configured, disabled, or quota exhausted.")

    clean_messages = _prepare_messages_for_groq(messages)

    headers = {
        "Authorization": f"Bearer {settings.GROQ_API_KEY}",
        "Content-Type": "application/json"
    }

    model = getattr(settings, "GROQ_MODEL", "openai/gpt-oss-120b")

    payload: Dict[str, Any] = {
        "model": model,
        "messages": clean_messages,
        "temperature": temperature,
        "max_tokens": max_tokens
    }

    if tools:
        payload["tools"] = tools
        payload["tool_choice"] = "auto"

    try:
        async with httpx.AsyncClient(timeout=35.0) as client:
            resp = await client.post(GROQ_API_BASE, json=payload, headers=headers)

            if resp.status_code in (429, 404) and "openai/gpt-oss-120b" in model:
                logger.info(f"[Groq] Status {resp.status_code} on primary model. Switching to backup model qwen/qwen3.8-27b...")
                payload["model"] = "qwen/qwen3.8-27b"
                resp = await client.post(GROQ_API_BASE, json=payload, headers=headers)

            if resp.status_code == 429:
                _groq_rate_limited_until = time.time() + 20.0
                logger.warning("[Groq] Rate limit reached (HTTP 429). Cooldown for 20s.")
                raise RuntimeError("Groq API rate limit (cooldown 20s).")

            if resp.status_code != 200:
                err_text = resp.text[:300]
                logger.warning(f"[Groq] API returned HTTP {resp.status_code}: {err_text}")
                raise RuntimeError(f"Groq API returned HTTP {resp.status_code}: {err_text}")

            data = resp.json()
            choices = data.get("choices", [])
            if not choices:
                raise RuntimeError("Groq returned empty choices.")

            msg = choices[0].get("message", {})
            raw_content = msg.get("content") or ""
            clean_content = _clean_reasoning_tags(raw_content)
            tool_calls = msg.get("tool_calls")

            return {
                "role": "assistant",
                "content": clean_content,
                "tool_calls": tool_calls,
                "is_groq": True,
                "is_simulated": False
            }

    except httpx.TimeoutException:
        logger.warning("[Groq] API request timed out after 35s.")
        raise RuntimeError("Groq API timed out.")
    except Exception as e:
        logger.warning(f"[Groq] Unexpected error: {e}")
        raise
